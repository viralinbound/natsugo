// Generates supabase/seed_lessons.sql from lib/curriculum.ts. Run: npm run db:lessons-sql
import { writeFileSync } from "node:fs";
import { lessonSeeds } from "../lib/curriculum.ts";

const q = (v) => (v === null || v === undefined ? "null" : typeof v === "number" || typeof v === "boolean" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const sql = `-- Generated by scripts/gen-lessons-sql.mjs
insert into public.lessons (id, level, unit, unit_title, sort, title, summary, duration_min, is_free) values
${lessonSeeds.map((l) => `  (${[l.id, l.level, l.unit, l.unitTitle, l.sort, l.title, l.summary, l.durationMin, l.isFree].map(q).join(", ")})`).join(",\n")}
on conflict (id) do update set unit = excluded.unit, unit_title = excluded.unit_title, sort = excluded.sort,
  title = excluded.title, summary = excluded.summary, duration_min = excluded.duration_min, is_free = excluded.is_free;

insert into public.lesson_assets (lesson_id, notes) values
${lessonSeeds.filter((l) => l.notes).map((l) => `  (${q(l.id)}, ${q(l.notes)})`).join(",\n")}
on conflict (lesson_id) do update set notes = excluded.notes;
`;
writeFileSync(new URL("../supabase/seed_lessons.sql", import.meta.url), sql, "utf8");
console.log(`${lessonSeeds.length} lessons, ${lessonSeeds.filter((l) => l.notes).length} with notes`);
