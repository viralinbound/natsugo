// Generates supabase/seed.sql from the starter content in lib/. Run: npm run db:seed-sql
// Then apply it with the Supabase SQL editor, `supabase db reset`, or the Supabase MCP.
import { writeFileSync } from "node:fs";
import { batches, teachers } from "../lib/data.ts";
import { words } from "../lib/words.ts";
import { quizBank } from "../lib/quizBank.ts";

const q = (v) => (v === null || v === undefined ? "null" : typeof v === "number" || typeof v === "boolean" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(",")}]::text[]`;
const rows = (list) => list.map((r) => `  (${r.join(", ")})`).join(",\n");

const sql = `-- Generated by scripts/gen-seed-sql.mjs — starter content (safe to re-run).
insert into public.teachers (id, name, role, experience_years, levels, specialization, sort) values
${rows(teachers.map((t, i) => [q(t.id), q(t.name), q(t.role), t.experienceYears ? q(t.experienceYears) : "null", arr(t.levels), q(t.specialization), q(i)]))}
on conflict (id) do nothing;

insert into public.batches (id, course_slug, course_title, level, mode, days, time_of_day, goal, start_date, schedule, duration_hours, seats_total, seats_left, price_label, teacher_id) values
${rows(batches.map((b) => [q(b.id), q(b.courseSlug), q(b.courseTitle), q(b.level), q(b.mode), q(b.days), q(b.time), q(b.goal), q(b.startISO), q(b.schedule), q(b.durationHours), q(Math.max(b.seatsLeft, 12)), q(b.seatsLeft), q(b.priceLabel), q(b.teacherId ?? null)]))}
on conflict (id) do nothing;

insert into public.words (jp, reading, romaji, meaning, example_jp, example_en, level)
select * from (values
${rows(words.map((w) => [q(w.jp), q(w.reading), q(w.romaji), q(w.meaning), q(w.example_jp), q(w.example_en), q(w.level)]))}
) v(jp, reading, romaji, meaning, example_jp, example_en, level)
where not exists (select 1 from public.words);

insert into public.settings (key, value) values
  ('announcement', '{"text": "New Japanese batches starting soon • Take your free level test", "enabled": true}'::jsonb)
on conflict (key) do nothing;

insert into public.quiz_questions (id, level, difficulty, skill, prompt, audio, options, answer, explanation, sort) values
${rows(quizBank.map((x, i) => [q(x.id), q(x.level), q(x.difficulty), q(x.skill), q(x.prompt), q(x.audio ?? null), arr(x.options), q(x.answer), q(x.explanation), q(i)]))}
on conflict (id) do update set prompt = excluded.prompt, audio = excluded.audio, options = excluded.options,
  answer = excluded.answer, explanation = excluded.explanation, skill = excluded.skill, sort = excluded.sort;
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql, "utf8");
console.log(`supabase/seed.sql written: ${teachers.length} teachers, ${batches.length} batches, ${words.length} words, ${quizBank.length} quiz questions`);
